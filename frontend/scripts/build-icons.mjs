/**
 * Bundles only the Solar icons the source uses, so pages never fetch icons at runtime
 * (Telegram clients in restricted networks cannot reach the Iconify API).
 *
 * Usage in code: <Icon name="solar:wallet-bold" />. Any "solar:<name>" string under src/
 * is picked up; an unknown name fails the build so a typo never ships a blank glyph.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src");
// Icon names the backend sends as data (the panel navigation) live in its Python modules.
const backendDir = join(root, "..", "app");
const outFile = join(srcDir, "icons", "solar-data.ts");
const solar = JSON.parse(readFileSync(join(root, "node_modules/@iconify-json/solar/icons.json"), "utf8"));

const NAME = /solar:([a-z0-9]+(?:-[a-z0-9]+)*)/g;

function walk(dir, pattern, files = []) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    // Built output (app/web/static) is not a source of names.
    if (path === outFile || entry === "static" || entry === "__pycache__") continue;
    if (statSync(path).isDirectory()) walk(path, pattern, files);
    else if (pattern.test(entry)) files.push(path);
  }
  return files;
}

const used = new Set();
for (const file of [...walk(srcDir, /\.(tsx?|jsx?)$/), ...walk(backendDir, /\.py$/)]) {
  for (const match of readFileSync(file, "utf8").matchAll(NAME)) used.add(match[1]);
}

function resolve(name) {
  if (solar.icons[name]) return solar.icons[name];
  const alias = solar.aliases?.[name];
  return alias ? resolve(alias.parent) : null;
}

const missing = [];
const data = {};
for (const name of [...used].sort()) {
  const icon = resolve(name);
  if (!icon) missing.push(name);
  else data[`solar:${name}`] = { body: icon.body, width: icon.width ?? solar.width ?? 24, height: icon.height ?? solar.height ?? 24 };
}

if (missing.length) {
  console.error(`Unknown Solar icon(s): ${missing.join(", ")}`);
  process.exit(1);
}

const banner = "// Generated by scripts/build-icons.mjs from @iconify-json/solar. Do not edit.\n";
const body = `export const SOLAR_ICONS: Record<string, { body: string; width: number; height: number }> = ${JSON.stringify(data, null, 1)};\n`;
writeFileSync(outFile, banner + body);
console.log(`icons: ${Object.keys(data).length} bundled`);
